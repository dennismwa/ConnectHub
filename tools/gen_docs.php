<?php
/** Generates docs/API-INDEX.md and docs/SETTINGS.md. Run: php tools/gen_docs.php */
require dirname(__DIR__) . '/includes/bootstrap.php';
$out = "# API index (generated by tools/gen_docs.php)\n\nSignatures of every core helper. Read the function body in the named file before relying on edge-case behaviour.\n\n";
foreach (array_merge(glob(ROOT . '/includes/*.php'), glob(ROOT . '/includes/lib/*.php')) as $f) {
    $src = file_get_contents($f);
    if (!preg_match_all('/^((?:\/\*\*(?:(?!\*\/).)*\*\/\s*)?)function (&?[a-z_0-9]+)\(([^)]*)\)(\s*:\s*[^\s{]+)?/ms', $src, $m, PREG_SET_ORDER)) { continue; }
    $out .= '## ' . str_replace(ROOT . '/', '', $f) . "\n\n";
    foreach ($m as $x) {
        $doc = trim(preg_replace('/^\s*\/?\*+\/?\s?/m', '', $x[1]));
        $doc = trim(preg_replace('/\s+/', ' ', $doc));
        $out .= '- `' . $x[2] . '(' . preg_replace('/\s+/', ' ', $x[3]) . ')' . trim($x[4] ?? '') . '`' . ($doc !== '' ? ' - ' . $doc : '') . "\n";
    }
    $out .= "\n";
}
file_put_contents(ROOT . '/docs/API-INDEX.md', $out);

$s = settings_schema();
$o = "# Settings catalogue (generated)\n\n`setting('key')` returns the typed value. Defaults shown. " . count($s['fields']) . " keys.\n\n";
foreach ($s['tabs'] as $tk => $tab) {
    $o .= "## {$tab['label']} (`$tk`)\n\n";
    foreach ($tab['sections'] as $sec) {
        $o .= "### {$sec['title']}\n\n";
        foreach ($sec['keys'] as $k) {
            $d = $s['fields'][$k];
            $def = is_scalar($d['default']) ? (string)$d['default'] : json_encode($d['default']);
            if (strlen($def) > 60) { $def = substr($def, 0, 57) . '...'; }
            $opts = isset($d['options']) ? ' options: ' . implode('|', array_keys($d['options'])) : '';
            $o .= "- `$k` ({$d['type']}, default `" . str_replace('`', "'", $def) . "`$opts) - {$d['label']}\n";
        }
        $o .= "\n";
    }
}
file_put_contents(ROOT . '/docs/SETTINGS.md', $o);
echo "ok\n";
